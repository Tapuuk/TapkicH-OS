"""`tapkich-boot-update`: keep Limine's boot menu, the files it loads and the Secure Boot signatures in step.

There are three locks on the boot chain (docs/boot-locks.md):
  1. path hashes: every kernel/initramfs line in limine.conf ends in `#<blake2b>` of that file;
  2. the enrolled config hash: the blake2b of limine.conf itself, written into Limine's EFI file (`limine
     enroll-config`), so Limine refuses a changed config (and, with Secure Boot on, turns the editor off);
  3. Secure Boot signatures (sbctl) on Limine's EFI files and on the kernel.
A rebuilt initramfs changes its hash, so 1 goes stale; writing new hashes changes the config, so 2 goes stale;
enrolling writes into Limine's EFI file, so 3 goes stale. This module redoes all three, in that order, whenever
something changed: from pacman (zzzz-tapkich-boot-update.hook, after 90-mkinitcpio-install.hook and sbctl's
hook), from mkinitcpio (its post hook, so a manual `mkinitcpio -P` is covered), from kernel-install, at shutdown,
and after every package upgrade of tapkich-os.

One source: /etc/tapkich-os/limine.conf (no hashes; the file to edit). Both configs on the ESP (EFI/limine/ for
limine_x64.efi, EFI/BOOT/ for BOOTX64.EFI) are generated from it and are always identical.
Settings: /etc/tapkich-os/boot.conf (VERIFY_HASHES, BOOT_EDITOR; see BOOT_CONF).
Recovery: a copy of the last kernel and initramfs that started fine stays on the ESP with its own hash
(/boot/tapkich-good/<version>/), as the menu entry "TapkicH-OS (last known good)". A rebuild never touches it, so one
stale hash cannot block every entry.

Never half-updated: everything new is first built as `<file>.new` (Limine copied fresh from the package, then
enrolled, then signed: enrolling a signed file is what makes sbctl report "incorrect digest"). Only when every piece
is ready and checked is it moved into place, one config and its Limine file at a time, so each of the two boot paths
is always complete. On any error nothing is moved and the old files stay.
All paths go through `root`, so the installer (root=/mnt) and the tests (root=tmp) use the same code.
"""
