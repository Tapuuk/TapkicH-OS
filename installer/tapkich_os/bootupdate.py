# ---------------------------------------------------------------- hashes and Limine's EFI file

def blake2b_file(path: str) -> str:
    h = hashlib.blake2b()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def blake2b_text(text: str) -> str:
    return hashlib.blake2b(text.encode()).hexdigest()


ENROLL_MARK = b"++CONFIG_B2SUM_SIGNATURE++"
UNENROLLED = "0" * 128


def enrolled_hash(data: bytes) -> str | None:
    """The config hash enrolled into a Limine EFI file: 128 hex digits, all zeros when nothing is enrolled; None when
    the file is not a Limine binary."""
    i = data.find(ENROLL_MARK)
    if i < 0:
        return None
    return data[i + len(ENROLL_MARK):i + len(ENROLL_MARK) + 128].decode("ascii", "replace")


def _pe_security_dir(data: bytes) -> tuple:
    """(offset of the certificate-table entry in the header, its file offset, its size) of a PE file; raises
    ValueError when it is not one."""
    try:
        if data[:2] != b"MZ" or len(data) < 0x40:
            raise ValueError("not a PE file")
        pe = struct.unpack_from("<I", data, 0x3C)[0]
        if data[pe:pe + 4] != b"PE\0\0":
            raise ValueError("not a PE file")
        opt = pe + 24
        magic = struct.unpack_from("<H", data, opt)[0]
        entry = opt + (112 if magic == 0x20B else 96) + 4 * 8      # data directory 4: the certificate table
        off, size = struct.unpack_from("<II", data, entry)
    except struct.error:
        raise ValueError("not a PE file (truncated)")
    if size and off + size > len(data):
        raise ValueError("certificate table past the end of the file")
    return entry, off, size


def strip_signature(data: bytes) -> bytes:
    """The PE file without its Authenticode signature (the certificate table is the last thing in the file).
    Anything that is not a PE file comes back unchanged."""
    try:
        entry, off, size = _pe_security_dir(data)
    except ValueError:
        return data
    if not size:
        return data
    out = bytearray(data[:off])
    struct.pack_into("<II", out, entry, 0, 0)
    return bytes(out)


def limine_base(data: bytes) -> bytes:
    """A Limine EFI file as the package ships it: no signature, nothing enrolled. Equal for every copy made from the
    same Limine version, however it was enrolled and signed afterwards."""
    data = strip_signature(data)
    i = data.find(ENROLL_MARK)
    if i >= 0:
        j = i + len(ENROLL_MARK)
        data = data[:j] + UNENROLLED.encode() + data[j + 128:]
    return data


SHA256_OID = bytes.fromhex("0609608648016503040201")          # 2.16.840.1.101.3.4.2.1
SPC_INDIRECT_OID = bytes.fromhex("060a2b060104018237020104")   # 1.3.6.1.4.1.311.2.1.4


def authenticode_sha256(data: bytes) -> bytes:
    """The Authenticode digest of a PE file: everything except the checksum field, the certificate-table entry and
    the certificate table itself (the layout of the kernel's EFI stub and of Limine: sections in file order)."""
    entry, off, size = _pe_security_dir(data)
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    checksum = pe + 24 + 64
    end = off if size else len(data)
    h = hashlib.sha256()
    h.update(data[:checksum])
    h.update(data[checksum + 4:entry])
    h.update(data[entry + 8:end])
    return h.digest()


def signature_status(path: str, cert_der: bytes | None) -> str:
    """"unsigned", "ok" (signed by our key and unchanged since), "bad-digest" (the file changed after it was signed:
    what sbctl calls "incorrect digest"), "other-key", or "not-pe". The digest is compared exactly; the signer by our
    certificate inside the signature (the cryptographic check is the firmware's, and sbctl verify's)."""
    with open(path, "rb") as f:
        data = f.read()
    try:
        _, off, size = _pe_security_dir(data)
    except ValueError:
        return "not-pe"
    if not size:
        return "unsigned"
    blob = data[off:off + size]
    at = blob.find(SPC_INDIRECT_OID)
    at = blob.find(SHA256_OID + b"\x05\x00\x04\x20", max(at, 0))
    if at < 0:
        return "bad-digest"
    digest = blob[at + len(SHA256_OID) + 4:at + len(SHA256_OID) + 36]
    if digest != authenticode_sha256(data):
        return "bad-digest"
    if cert_der and cert_der not in blob:
        return "other-key"
    return "ok"


def kernel_version(path: str) -> str:
    """The version an x86 Linux bzImage reports (`uname -r` once it runs); "" when it cannot be read."""
    try:
        with open(path, "rb") as f:
            head = f.read(0x10000)
        if head[0x202:0x206] != b"HdrS":
            return ""
        off = struct.unpack_from("<H", head, 0x20E)[0] + 0x200
        return head[off:off + 128].split(b"\0")[0].split(b" ")[0].decode("ascii", "replace")
    except (OSError, struct.error):
        return ""


# ---------------------------------------------------------------- the config text (pure, unit-tested)

HASHED_KEYS = ("path", "module_path", "kernel_path", "dtb_path", "wallpaper", "term_font")
_FILE_LINE = re.compile(r"^(\s*)(" + "|".join(HASHED_KEYS) + r")(\s*:\s*)(boot\(\):)(/[^#\s]+)(#[0-9a-fA-F]*)?\s*$")
GENERATED_OPTIONS = ("editor_enabled", "hash_mismatch_panic")
_OPTION = re.compile(r"^(" + "|".join(GENERATED_OPTIONS) + r")\s*:", re.I)


def with_hashes(conf: str, hash_of) -> str:
    """limine.conf with a fresh `#<blake2b>` on every file on our ESP (`boot():/...`). `hash_of(relpath)` returns the
    hex hash, or None to leave the path without one. Windows (`guid(...)`, protocol efi) is left alone: the firmware
    checks Microsoft's signature on it."""
    out = []
    for line in conf.split("\n"):
        m = _FILE_LINE.match(line)
        if m:
            indent, key, sep, dev, rel, _old = m.groups()
            h = hash_of(rel.lstrip("/"))
            line = f"{indent}{key}{sep}{dev}{rel}" + (f"#{h}" if h else "")
        out.append(line)
    return "\n".join(out)


def without_hashes(conf: str) -> str:
    return with_hashes(conf, lambda rel: None)


def file_lines(conf: str) -> list:
    """[(key, relpath, hash or "")] for every ESP file the config loads."""
    out = []
    for line in conf.split("\n"):
        m = _FILE_LINE.match(line)
        if m:
            out.append((m.group(2), m.group(5).lstrip("/"), (m.group(6) or "").lstrip("#")))
    return out


def split_entries(conf: str) -> tuple:
    """(the lines before the first entry, [(title, lines of that top-level entry incl. its sub-entries)])."""
    head, entries = [], []
    for line in conf.split("\n"):
        if line.startswith("/") and not line.startswith("//"):
            entries.append((line[1:].strip(), [line]))
        elif entries:
            entries[-1][1].append(line)
        else:
            head.append(line)
    return head, entries


def to_source(conf: str) -> str:
    """A generated limine.conf turned back into its source: no header, no generated options, no hashes, no
    last-known-good entry. source -> generate -> to_source gives the source back."""
    conf = conf.replace("\r\n", "\n")
    if conf.startswith("# Generated by tapkich-boot-update"):      # our header: the comment lines at the top
        lines = conf.split("\n")
        while lines and lines[0].startswith("#"):
            lines.pop(0)
        conf = "\n".join(lines)
    head, entries = split_entries(without_hashes(conf))
    head = [l for l in head if not _OPTION.match(l.strip())]
    body = "\n".join(head)
    for title, lines in entries:
        if title != GOOD_TITLE:
            body += ("\n" if body else "") + "\n".join(lines)
    return body.rstrip("\n") + "\n"


def _first_linux_entry(entries: list) -> dict:
    """path, module_path and cmdline of the first `protocol: linux` entry (TapkicH-OS itself)."""
    for _, lines in entries:
        opts = {}
        for l in lines[1:]:
            m = re.match(r"^\s*(\w+)\s*:\s*(.*?)\s*$", l)
            if m and m.group(1) not in opts:
                opts[m.group(1)] = m.group(2)
        if opts.get("protocol") == "linux" and opts.get("path", "").startswith("boot():/"):
            return opts
    return {}


def main_files(source: str) -> tuple:
    """(kernel, initramfs) of the main TapkicH-OS entry, relative to the ESP; ("", "") if there is none."""
    opts = _first_linux_entry(split_entries(source)[1])
    rel = lambda v: v.split("#")[0][len("boot():/"):] if v.startswith("boot():/") else ""
    return rel(opts.get("path", "")), rel(opts.get("module_path", ""))


def good_entry(source: str, good: str) -> list:
    """The "last known good" entry for the copy in GOOD_DIR/<good>/ (its kernel and initramfs keep their own names)."""
    opts = _first_linux_entry(split_entries(source)[1])
    kernel, initrd = main_files(source)
    if not opts or not kernel or not initrd:
        return []
    return [
        f"/{GOOD_TITLE}",
        f"    comment: the kernel and initramfs that last started fine ({good.rsplit('-g', 1)[0]}); "
        "use it when the others fail",
        "    protocol: linux",
        f"    path: boot():/{GOOD_DIR}/{good}/{os.path.basename(kernel)}",
        f"    cmdline: {opts.get('cmdline', '')}",
        f"    module_path: boot():/{GOOD_DIR}/{good}/{os.path.basename(initrd)}",
    ]


def generate(source: str, *, verify: bool, editor: bool, hash_of, good: str = "") -> str:
    """The limine.conf written to both places on the ESP. `hash_of(relpath)` as in with_hashes (only called when
    verify). With verify, `hash_mismatch_panic: no` lets a stale hash be overridden with Y while Secure Boot is off
    (with it on Limine forces the panic, by design)."""
    head, entries = split_entries(to_source(source).rstrip("\n"))
    while head and not head[-1].strip():
        head.pop()
    opts = [f"editor_enabled: {'yes' if editor else 'no'}"]
    if verify:
        opts.append("hash_mismatch_panic: no")
    # the copy goes after TapkicH-OS's own entries, before Windows
    win = next((i for i, (t, _) in enumerate(entries) if t.startswith("Windows")), len(entries))
    extra = good_entry(source, good) if good else []
    if extra:
        entries.insert(win, (GOOD_TITLE, extra))
    body = []
    for _, lines in entries:
        lines = list(lines)
        while lines and not lines[-1].strip():
            lines.pop()
        body.append("\n".join(lines))
    text = HEADER + "\n".join(opts + head) + "\n\n" + "\n\n".join(body) + "\n"
    return with_hashes(text, hash_of) if verify else text


# ---------------------------------------------------------------- settings

def read_kv(path: str) -> dict:
    try:
        with open(path) as f:
            return dict(l.strip().split("=", 1) for l in f if "=" in l and not l.lstrip().startswith("#"))
    except OSError:
        return {}


def settings(root: str, warn=print) -> dict:
    """VERIFY_HASHES (auto|yes|no) and BOOT_EDITOR (auto|on|off); a value we do not know counts as auto (a typo must
    never stop the boot menu from being updated)."""
    kv = read_kv(os.path.join(root, SETTINGS))
    out = {}
    for key, allowed in (("VERIFY_HASHES", ("auto", "yes", "no")), ("BOOT_EDITOR", ("auto", "on", "off"))):
        v = kv.get(key, "auto").strip().strip("\"'").lower()
        if v not in allowed:
            warn(f"tapkich-boot-update: {key}={v!r} in /{SETTINGS} is not one of {'|'.join(allowed)}; using auto")
            v = "auto"
        out[key] = v
    return out


def secure_boot_on(efivars: str = EFIVARS) -> bool | None:
    """Secure Boot enforced by the firmware right now; None when it cannot be read (legacy boot, no efivars)."""
    def var(name):
        try:
            with open(f"{efivars}/{name}-{EFI_GLOBAL}", "rb") as f:
                d = f.read()
            return d[-1] == 1 if len(d) > 4 else None
        except OSError:
            return None
    sb, setup = var("SecureBoot"), var("SetupMode")
    return None if sb is None else (sb and not setup)


def resolve(s: dict, sb_on: bool | None) -> tuple:
    """(verify, editor). Unknown Secure Boot state counts as off: with no hashes Limine starts either way."""
    on = bool(sb_on)
    verify = s["VERIFY_HASHES"] == "yes" or (s["VERIFY_HASHES"] == "auto" and on)
    editor = s["BOOT_EDITOR"] == "on" or (s["BOOT_EDITOR"] == "auto" and not on)
    return verify, editor


# ---------------------------------------------------------------- doing it

def _run(cmd: list, check: bool = True) -> subprocess.CompletedProcess:
    p = subprocess.run(cmd, capture_output=True, text=True)
    if check and p.returncode != 0:
        raise BootUpdateError(f"{' '.join(cmd)} failed (exit {p.returncode}): {(p.stderr or p.stdout).strip()[-400:]}")
    return p


def _pem_der(path: str) -> bytes | None:
    import base64
    try:
        with open(path) as f:
            m = re.search(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", f.read(), re.S)
        return base64.b64decode("".join(m.group(1).split())) if m else None
    except (OSError, ValueError):
        return None


def has_keys(root: str) -> bool:
    """sbctl has created our Secure Boot keys (root-only directories: False when they cannot be read)."""
    for d in SBCTL_KEYS:
        try:
            if os.listdir(os.path.join(root, d)):
                return True
        except OSError:
            pass
    return False


class Machine:
    """Where everything is, and how commands run. `run` and `sb_on` are replaced in tests; `sign` defaults to
    "sbctl has keys" (only on the running system: a root other than / never signs with the host's keys)."""

    def __init__(self, root: str = "/", *, run=None, sb_on="read", sign=None, log=print, efivars: str = EFIVARS):
        self.root = root
        self.boot = os.path.join(root, BOOT)
        self.run = run or _run
        self.log = log
        self.sb_on = secure_boot_on(efivars) if sb_on == "read" else sb_on
        if sign is None:
            sign = root == "/" and bool(shutil.which("sbctl")) and has_keys(root)
        self.sign = sign
        self.cert = next((c for c in (_pem_der(os.path.join(root, p)) for p in DB_CERT) if c), None)
        self.running = os.uname().release if root == "/" else ""     # the kernel this system started with
        self.boot_time = _boot_time

    def esp(self, rel: str) -> str:
        return os.path.join(self.boot, rel)

    def at(self, rel: str) -> str:
        return os.path.join(self.root, rel)


def _write(path: str, data, mode="w") -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, mode) as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())


def _replace(path: str, data, mode="w") -> None:
    _write(path + ".new", data, mode)
    os.replace(path + ".new", path)


def _sync_dir(path: str) -> None:
    try:
        fd = os.open(path, os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    except OSError:
        pass


def read_source(m: Machine, create: bool = True) -> str:
    """/etc/tapkich-os/limine.conf. Systems from before it existed get it made from the ESP's config (once)."""
    src = m.at(SOURCE)
    try:
        with open(src) as f:
            return f.read()
    except FileNotFoundError:
        pass
    for c in LIMINE_CONFS:
        try:
            with open(m.esp(c), newline="") as f:
                text = to_source(f.read())
        except OSError:
            continue
        if create:
            _replace(src, text)
            m.log(f"  made /{SOURCE} from the boot partition's limine.conf (edit that file from now on)")
        return text
    raise NotSetUp(f"no TapkicH-OS boot menu found (no /{SOURCE} and no limine.conf on {m.boot})")


def write_source(m: Machine, text: str) -> None:
    _replace(m.at(SOURCE), to_source(text))


def _good_sets(m: Machine) -> list:
    d = m.esp(GOOD_DIR)
    try:
        return sorted(n for n in os.listdir(d) if not n.endswith(".new") and os.path.isdir(os.path.join(d, n)))
    except OSError:
        return []


def _current_good(m: Machine, source: str) -> str:
    """The known-good copy in use: the one the state file names, if all of its files are there."""
    name = read_kv(m.at(STATE)).get("good", "")
    kernel, initrd = main_files(source)
    if name and kernel and initrd and all(os.path.isfile(m.esp(f"{GOOD_DIR}/{name}/{os.path.basename(f)}"))
                                          for f in (kernel, initrd)):
        return name
    return ""


def _boot_time() -> float:
    with open("/proc/uptime") as f:
        return time.time() - float(f.read().split()[0])


def promote_good(m: Machine, source: str) -> str:
    """Copy the kernel and initramfs this system just started with into GOOD_DIR/<version>-g<hash>/. Returns the new
    set's name, or "" when there is nothing to do or it cannot be done safely (that is never an error)."""
    kernel, initrd = main_files(source)
    if not m.running or not kernel or not initrd:
        return ""
    k, i = m.esp(kernel), m.esp(initrd)
    if not (os.path.isfile(k) and os.path.isfile(i)):
        return ""
    running = m.running
    if kernel_version(k) != running:
        m.log(f"  last known good: kept (this start used {running}, /boot now has {kernel_version(k) or 'another kernel'})")
        return ""
    try:
        started = m.boot_time()
    except (OSError, ValueError, IndexError):
        return ""
    if max(os.path.getmtime(k), os.path.getmtime(i)) > started:
        m.log("  last known good: kept (the kernel or initramfs changed after this start)")
        return ""
    name = f"{running}-g{blake2b_file(i)[:12]}"
    if name == _current_good(m, source) or name in _good_sets(m):
        return name
    need = os.path.getsize(k) + os.path.getsize(i) + GOOD_MARGIN
    if shutil.disk_usage(m.boot).free < need:
        m.log(f"  last known good: not updated, the boot partition has less than {need // 2**20} MiB free")
        return ""
    tmp = m.esp(f"{GOOD_DIR}/{name}.new")
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)
    for f in (k, i):
        shutil.copyfile(f, os.path.join(tmp, os.path.basename(f)))
        with open(os.path.join(tmp, os.path.basename(f)), "rb") as fh:
            os.fsync(fh.fileno())
    os.replace(tmp, m.esp(f"{GOOD_DIR}/{name}"))
    m.log(f"  last known good: {name}")
    return name


def _sign_kernel(m: Machine, path: str) -> bool:
    """Sign a kernel with our key unless it already carries a valid signature of ours. A stale signature (changed
    after signing: "incorrect digest") is stripped first. Done on a copy that replaces the file, so a failure leaves
    the old kernel. Returns True when the file changed."""
    st = signature_status(path, m.cert)
    if st == "ok":
        return False
    if st == "not-pe":
        raise BootUpdateError(f"{path} is not a kernel image (not a PE file)")
    with open(path, "rb") as f:
        data = strip_signature(f.read())
    tmp = path + ".new"
    unsigned = path + ".unsigned"
    try:
        _write(unsigned, data, "wb")
        m.run(["sbctl", "sign", "-o", tmp, unsigned])
        if signature_status(tmp, m.cert) != "ok":
            raise BootUpdateError(f"signing {path} did not give a valid signature")
        with open(tmp, "rb") as fh:
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    finally:
        for p in (tmp, unsigned):
            if os.path.lexists(p):
                os.remove(p)
    m.run(["sbctl", "sign", "-s", path], check=False)          # in sbctl's database, for its own hook (already signed)
    m.log(f"  signed {os.path.relpath(path, m.boot)}" + (" (its old signature was stale)" if st == "bad-digest" else ""))
    return True


def _efi_current(m: Machine, path: str, want_hash: str, base: bytes) -> bool:
    try:
        with open(path, "rb") as f:
            data = f.read()
    except OSError:
        return False
    if enrolled_hash(data) != want_hash or limine_base(data) != base:
        return False
    return signature_status(path, m.cert) == "ok" if m.sign else True


def update(m: Machine, *, force: bool = False, mark_good: bool = False) -> bool:
    """Bring both configs, both Limine files and the signatures in line with the source and the files on the ESP.
    Returns True when something was written. Raises BootUpdateError (nothing moved into place) on failure."""
    if not os.path.isdir(m.esp("EFI/limine")):
        if m.root == "/" and os.path.isdir(m.boot) and not os.path.ismount(m.boot) and os.listdir(m.boot):
            raise NotSetUp("/boot is not the EFI partition (it is not mounted): mount it first (see "
                           "/usr/share/doc/tapkich-os/boot-recovery.md). Files written there are not what starts.")
        raise NotSetUp(f"no Limine on {m.boot} (EFI/limine is missing)")
    s = settings(m.root, warn=m.log)
    verify, editor = resolve(s, m.sb_on)
    source = read_source(m)
    state = read_kv(m.at(STATE))
    good = promote_good(m, source) if mark_good else ""
    good = good or _current_good(m, source)

    if m.sign:                                     # signing changes the kernel: it comes before its hash
        kernel, _ = main_files(source)
        for rel in [kernel] + ([f"{GOOD_DIR}/{good}/{os.path.basename(kernel)}"] if good and kernel else []):
            if rel and os.path.isfile(m.esp(rel)):
                _sign_kernel(m, m.esp(rel))

    def hash_of(rel):
        p = m.esp(rel)
        return blake2b_file(p) if os.path.isfile(p) else None

    text = generate(source, verify=verify, editor=editor, hash_of=hash_of, good=good)
    missing = [rel for key, rel, h in file_lines(text) if key not in ("wallpaper", "term_font")
               and not os.path.isfile(m.esp(rel))]
    if missing:
        raise BootUpdateError("these boot files are missing, so the menu would not start them: " + ", ".join(missing))
    want_hash = blake2b_text(text) if verify else UNENROLLED
    src_efi = m.at(LIMINE_SRC)
    if not os.path.isfile(src_efi):
        raise BootUpdateError(f"/{LIMINE_SRC} is missing (is the limine package installed?)")
    with open(src_efi, "rb") as f:
        base = limine_base(f.read())

    todo = []
    for conf_rel, efi_rel in zip(LIMINE_CONFS, LIMINE_EFIS):
        try:
            with open(m.esp(conf_rel), newline="") as f:
                conf_ok = f.read() == text
        except OSError:
            conf_ok = False
        if force or not conf_ok or not _efi_current(m, m.esp(efi_rel), want_hash, base):
            todo.append((conf_rel, efi_rel))

    if todo:
        _install(m, todo, text, want_hash, verify, src_efi)
        m.log("  boot menu: " + ("hashes written, config hash enrolled" if verify else "no hashes (VERIFY_HASHES "
              f"{s['VERIFY_HASHES']}), nothing enrolled") + (", Limine signed" if m.sign else "")
              + f", editor {'on' if editor else 'off'}")
    if good != state.get("good", ""):
        state["good"] = good
    for name in _good_sets(m) + [n for n in _listdir(m.esp(GOOD_DIR)) if n.endswith(".new")]:
        if name != good:                          # older copies: the config no longer names them
            shutil.rmtree(m.esp(f"{GOOD_DIR}/{name}"), ignore_errors=True)
    state.update(verify="yes" if verify else "no", editor="on" if editor else "off", config=blake2b_text(text))
    os.makedirs(os.path.dirname(m.at(STATE)), exist_ok=True)
    _replace(m.at(STATE), "".join(f"{k}={v}\n" for k, v in sorted(state.items())))
    problems = [p for p in check(m) if p[0] == "error"]
    if problems:
        raise BootUpdateError("after the update these are still wrong: " + "; ".join(t for _, t in problems))
    return bool(todo)


def _listdir(d: str) -> list:
    try:
        return os.listdir(d)
    except OSError:
        return []


def _install(m: Machine, pairs: list, text: str, want_hash: str, verify: bool, src_efi: str) -> None:
    """Stage every new file as <file>.new and check it, then move them into place pair by pair."""
    staged = [m.esp(x) + ".new" for pair in pairs for x in pair]
    src_size = os.path.getsize(src_efi)
    need = len(pairs) * (src_size + SIGN_MARGIN + len(text.encode()))
    free = shutil.disk_usage(m.boot).free
    if free < need:
        raise BootUpdateError(f"not enough free space on the boot partition: {need // 1024} KiB needed, "
                              f"{free // 1024} KiB free. Nothing was changed.")
    try:
        for p in staged:
            if os.path.lexists(p):
                os.remove(p)
        for conf_rel, efi_rel in pairs:
            conf_new, efi_new = m.esp(conf_rel) + ".new", m.esp(efi_rel) + ".new"
            _write(conf_new, text)
            os.makedirs(os.path.dirname(efi_new), exist_ok=True)
            shutil.copyfile(src_efi, efi_new)              # a clean binary each time: enroll first, then sign
            if verify:
                m.run(["limine", "enroll-config", "--quiet", efi_new, want_hash])
            if m.sign:
                m.run(["sbctl", "sign", efi_new])
            with open(efi_new, "rb") as f:
                data = f.read()
            if enrolled_hash(data) != want_hash or len(data) < src_size:
                raise BootUpdateError(f"the new {efi_rel} is not right (enrolled hash or size); the old files were kept")
            if m.sign and signature_status(efi_new, m.cert) != "ok":
                raise BootUpdateError(f"the new {efi_rel} is not signed correctly; the old files were kept")
            with open(efi_new, "rb") as f:
                os.fsync(f.fileno())
            with open(conf_new) as f:
                if blake2b_text(f.read()) != blake2b_text(text):
                    raise BootUpdateError(f"the new {conf_rel} did not read back correctly; the old files were kept")
        for conf_rel, efi_rel in pairs:                    # each directory is a complete boot path on its own
            os.replace(m.esp(conf_rel) + ".new", m.esp(conf_rel))
            os.replace(m.esp(efi_rel) + ".new", m.esp(efi_rel))
            _sync_dir(os.path.dirname(m.esp(conf_rel)))
    finally:
        for p in staged:
            try:
                os.remove(p)
            except OSError:
                pass


# ---------------------------------------------------------------- checking (read-only)

def check(m: Machine) -> list:
    """[(level, text)]: "error" for what would stop a start or leaves a lock stale, "warn" for what is not as
    configured but still starts, "ok" for what is fine."""
    out = []
    try:
        source = read_source(m, create=False)
    except NotSetUp as e:
        return [("error", str(e))]
    except PermissionError:
        return [("error", "cannot read the boot files: run it with sudo")]
    if not os.path.isfile(m.at(SOURCE)):
        out.append(("warn", f"/{SOURCE} does not exist yet (the next update makes it from the boot partition)"))
    s = settings(m.root, warn=lambda *_: None)
    verify, editor = resolve(s, m.sb_on)
    sb = {True: "on", False: "off", None: "unknown"}[m.sb_on]
    out.append(("ok", f"settings: VERIFY_HASHES={s['VERIFY_HASHES']} -> {'yes' if verify else 'no'}, BOOT_EDITOR="
                      f"{s['BOOT_EDITOR']} -> {'on' if editor else 'off'} (Secure Boot {sb})"))
    try:
        texts = {}
        for c in LIMINE_CONFS:
            try:
                with open(m.esp(c), newline="") as f:
                    texts[c] = f.read()
            except FileNotFoundError:
                out.append(("error", f"{c} is missing"))
        if len(set(texts.values())) > 1:
            out.append(("error", "the two limine.conf files differ"))
        for c, text in texts.items():
            for key, rel, h in file_lines(text):
                p = m.esp(rel)
                soft = key in ("wallpaper", "term_font")
                if not os.path.isfile(p):
                    out.append(("warn" if soft else "error", f"{c}: {rel} does not exist"))
                elif h and h.lower() != blake2b_file(p):
                    out.append(("warn" if soft else "error", f"{c}: the hash for {rel} does not match the file "
                                "(it changed after the config was written: Limine refuses or warns)"))
                elif not h and verify and not soft:
                    out.append(("error", f"{c}: {rel} has no hash (VERIFY_HASHES is on)"))
            if to_source(text) != to_source(generate(source, verify=False, editor=editor, hash_of=None,
                                                     good=_current_good(m, source))):
                out.append(("warn", f"{c} is not generated from the current /{SOURCE}"))
        try:
            with open(m.at(LIMINE_SRC), "rb") as f:
                base = limine_base(f.read())
        except OSError:
            base = None
            out.append(("warn", f"/{LIMINE_SRC} is missing: cannot tell whether Limine is current"))
        for conf_rel, efi_rel in zip(LIMINE_CONFS, LIMINE_EFIS):
            try:
                with open(m.esp(efi_rel), "rb") as f:
                    data = f.read()
            except FileNotFoundError:
                out.append(("error", f"{efi_rel} is missing"))
                continue
            got = enrolled_hash(data)
            if got is None:
                out.append(("error", f"{efi_rel} is not a Limine binary"))
                continue
            text = texts.get(conf_rel)
            if got != UNENROLLED and text is not None and got != blake2b_text(text):
                out.append(("error", f"{efi_rel}: the enrolled config hash does not match {conf_rel} (Limine panics: "
                                     "config checksum mismatch)"))
            elif got == UNENROLLED and verify:
                out.append(("error", f"{efi_rel}: no config hash enrolled (VERIFY_HASHES is on)"))
            elif got != UNENROLLED and not verify:
                out.append(("warn", f"{efi_rel}: a config hash is enrolled but VERIFY_HASHES is off"))
            if base is not None and limine_base(data) != base:
                out.append(("warn", f"{efi_rel} is not the installed Limine version (or was changed)"))
            if m.sign:
                st = signature_status(m.esp(efi_rel), m.cert)
                if st != "ok":
                    out.append(("error", f"{efi_rel}: Secure Boot signature {st}"))
        if m.sign:
            kernel, _ = main_files(source)
            good = _current_good(m, source)
            for rel in [kernel] + ([f"{GOOD_DIR}/{good}/{os.path.basename(kernel)}"] if good and kernel else []):
                if rel and os.path.isfile(m.esp(rel)):
                    st = signature_status(m.esp(rel), m.cert)
                    if st != "ok":
                        out.append(("error", f"{rel}: Secure Boot signature {st}"))
        good = _current_good(m, source)
        out.append(("ok" if good else "warn", f"last known good copy: {good}" if good else
                    "no last known good copy yet (made a few minutes after a start)"))
    except PermissionError:
        return [("error", "cannot read the boot files: run it with sudo")]
    return out


def sbctl_verify(m: Machine) -> list:
    """[(level, text)] from `sbctl verify`: every EFI file sbctl finds on the ESP, and whether it is signed."""
    p = m.run(["sbctl", "verify", "--json"], check=False)
    out = []
    try:
        items = json.loads(p.stdout or "[]")
        for it in items if isinstance(items, list) else []:
            name = it.get("file_name") or it.get("file") or "?"
            ok = it.get("is_signed") in (1, True)
            out.append(("ok" if ok else "error", f"sbctl verify: {name} {'is signed' if ok else 'is NOT signed'}"))
    except ValueError:
        p = m.run(["sbctl", "verify"], check=False)
        for line in (p.stdout + p.stderr).splitlines():
            if "✗" in line or "not signed" in line:
                out.append(("error", "sbctl verify: " + line.strip("✗ ").strip()))
            elif "✓" in line:
                out.append(("ok", "sbctl verify: " + line.strip("✓ ").strip()))
    if p.returncode != 0 and not any(l == "error" for l, _ in out):
        out.append(("error", f"sbctl verify failed (exit {p.returncode}): {(p.stderr or p.stdout).strip()[-200:]}"))
    if not out:
        out.append(("error", "sbctl verify listed no files"))
    return out


def secure_boot_check(m: Machine) -> list:
    """Everything that must hold before Secure Boot is switched on, read-only."""
    from . import secureboot
    out = []
    if not shutil.which("sbctl"):
        return [("error", "sbctl is not installed: run `sudo tapkich secureboot setup`")]
    if not has_keys(m.root):
        return [("error", "no Secure Boot keys yet: run `sudo tapkich secureboot setup`")]
    m.sign = True
    st = secureboot.read_state(m.root)
    if st.get("setup_mode"):
        out.append(("error", "the firmware is in Setup Mode: our keys are not enrolled yet (`sudo tapkich secureboot setup`)"))
    elif not st.get("tapkich_key_in_db"):
        out.append(("error", "our key is not in the firmware's key database: the firmware would refuse Limine"))
    else:
        out.append(("ok", "our key is enrolled in the firmware"))
    if not (st.get("ms_in_db") or st.get("ms_in_kek")):
        out.append(("warn", "no Microsoft keys in the firmware: Windows and graphics card firmware may not start"))
    out += check(m)
    out += sbctl_verify(m)
    verify, _ = resolve(settings(m.root, warn=lambda *_: None), True)
    if verify and read_kv(m.at(STATE)).get("verify") != "yes":
        out.append(("ok", "file hashes: off now, switched on by itself at the first start with Secure Boot on "
                          "(VERIFY_HASHES=auto); until then Limine starts without checking the files"))
    elif not verify:
        out.append(("warn", "VERIFY_HASHES=no: with Secure Boot on, Limine still starts any kernel on the ESP"))
    return out


# ---------------------------------------------------------------- command

def _lock(m: Machine):
    path = m.at(LOCK) if os.path.isdir(m.at("run")) else os.path.join(m.root, "tmp", "tapkich-boot-update.lock")
    fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o600)
    fcntl.flock(fd, fcntl.LOCK_EX)                 # pacman, mkinitcpio and the shutdown unit can start it together
    return fd


def _report(items: list, quiet_ok: bool = False) -> int:
    mark = {"ok": "[ ok ]", "warn": "[warn]", "error": "[FAIL]"}
    for level, text in items:
        if not (quiet_ok and level == "ok"):
            print(f"{mark[level]} {text}")
    return 1 if any(l == "error" for l, _ in items) else 0


def main(args: list) -> int:
    known = {"--check", "--force", "--hook", "--mark-good", "--secure-boot-check", "--help", "-h"}
    if any(a not in known for a in args):
        print(USAGE, file=sys.stderr)
        return 2
    if "--help" in args or "-h" in args:
        print(USAGE)
        return 0
    hook = "--hook" in args
    if os.geteuid() != 0:                           # the boot partition and the keys are root-only
        if hook or not sys.stdin.isatty():
            print("tapkich-boot-update: needs root (sudo)", file=sys.stderr)
            return 1
        here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        os.execvp("sudo", ["sudo", "env", f"PYTHONPATH={here}", "PYTHONDONTWRITEBYTECODE=1", sys.executable, "-P", "-m",
                           "tapkich_os.bootupdate", *args])
    m = Machine("/", log=(lambda *_: None) if hook else print)
    if "--secure-boot-check" in args:
        items = secure_boot_check(m)
        code = _report(items)
        print("\nSafe to turn Secure Boot on." if code == 0 else
              "\nDo NOT turn Secure Boot on yet: fix the [FAIL] lines first (`sudo tapkich-boot-update` fixes most).")
        return code
    if "--check" in args:
        code = _report(check(m))
        print("\nEverything is in step." if code == 0 else "\nOut of step: `sudo tapkich-boot-update` fixes it.")
        return code
    lock = _lock(m)
    try:
        changed = update(m, force="--force" in args, mark_good="--mark-good" in args)
        if not hook:
            print("Boot menu updated." if changed else "Boot menu already up to date.")
        return 0
    except NotSetUp as e:
        if hook:                                    # an installer chroot, or no TapkicH-OS boot menu: nothing to keep
            if "not the EFI partition" in str(e):
                print(f"tapkich-boot-update: {e}", file=sys.stderr)
            return 0
        print(f"tapkich-boot-update: {e}", file=sys.stderr)
        return 1
    except (BootUpdateError, OSError) as e:
        print(f"tapkich-boot-update: FAILED: {e}\nThe old boot files were kept. Fix the cause and run "
              "`sudo tapkich-boot-update` again; `sudo tapkich-boot-update --check` shows the state.", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Stopped. The old boot files were kept.", file=sys.stderr)
        return 130
    finally:
        os.close(lock)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
