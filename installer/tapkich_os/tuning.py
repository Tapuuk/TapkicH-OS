"""System tuning shipped with TapkicH-OS (our own, replacing CachyOS' settings package).

Everything here is plain text generated by pure functions (unit-tested) and written into the installed system by
system.py. IMPORTANT: none of this has been measured for game performance yet. The plan is to measure
average FPS and 1% lows with MangoHud on real hardware before claiming any gain; a VM cannot show that.
"""
from __future__ import annotations

# Official Arch packages (extra). scx-scheds (sched-ext schedulers) is NOT installed until we have verified that the
# linux-zen build supports sched_ext (check /proc/config.gz for CONFIG_SCHED_CLASS_EXT) and measured a benefit.
TUNING_PACKAGES = ["zram-generator", "gamemode", "mangohud"]

ZRAM_GENERATOR_CONF = """# TapkicH-OS: compressed swap in RAM (zram). Half of the RAM, at most 8 GiB.
[zram0]
zram-size = min(ram / 2, 8192)
compression-algorithm = zstd
swap-priority = 100
"""

SYSCTL_CONF = """# TapkicH-OS: desktop + gaming defaults. Not measured yet.
# zram swap is cheap, so prefer it over dropping the page cache, and do not read ahead from it
vm.swappiness = 100
vm.page-cluster = 0
vm.vfs_cache_pressure = 50
# some games (and Proton) need many more memory mappings than the default 65530
vm.max_map_count = 2147483642
# avoids big slowdowns in some games on Intel CPUs
kernel.split_lock_mitigate = 0
kernel.nmi_watchdog = 0
# better latency under load for online games
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
"""

# Same rules as the Arch Wiki's "Improving performance" page: NVMe none, other SSDs mq-deadline, spinning disks bfq.
UDEV_IOSCHED = """# TapkicH-OS: I/O scheduler per device type
ACTION=="add|change", KERNEL=="nvme[0-9]*n[0-9]*", ATTR{queue/scheduler}="none"
ACTION=="add|change", KERNEL=="sd[a-z]*|mmcblk[0-9]*", ATTR{queue/rotational}=="0", ATTR{queue/scheduler}="mq-deadline"
ACTION=="add|change", KERNEL=="sd[a-z]*|mmcblk[0-9]*", ATTR{queue/rotational}=="1", ATTR{queue/scheduler}="bfq"
"""


def files() -> dict:
    """path (inside the installed system) -> file content."""
    return {
        "/etc/systemd/zram-generator.conf": ZRAM_GENERATOR_CONF,
        "/etc/sysctl.d/99-tapkich-os.conf": SYSCTL_CONF,
        "/etc/udev/rules.d/60-ioschedulers.rules": UDEV_IOSCHED,
    }
